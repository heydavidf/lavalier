import AppKit

/// Everything on a pasteboard at one moment: every item with every type it offers, in the order the item
/// listed them, read eagerly. Types that refuse to provide data are recorded in `unreadableTypes`.
public struct PasteboardSnapshot {
    public static let transientType = NSPasteboard.PasteboardType("org.nspasteboard.TransientType")
    public static let autoGeneratedType = NSPasteboard.PasteboardType("org.nspasteboard.AutoGeneratedType")

    public struct Item {
        public var types: [(type: NSPasteboard.PasteboardType, data: Data)]
    }

    public private(set) var items: [Item] = []
    public private(set) var unreadableTypes: [String] = []
    public let changeCount: Int

    public init(pasteboard: NSPasteboard) {
        changeCount = pasteboard.changeCount
        for item in pasteboard.pasteboardItems ?? [] {
            var entry = Item(types: [])
            for type in item.types {
                if let data = item.data(forType: type) {
                    entry.types.append((type, data))
                } else {
                    unreadableTypes.append(type.rawValue)
                }
            }
            if !entry.types.isEmpty { items.append(entry) }
        }
    }

    /// True when the pasteboard held nothing at all.
    public var isEmpty: Bool { items.isEmpty && unreadableTypes.isEmpty }

    /// True when something was there but none of it could be read (for example only file promises).
    public var isUnrestorable: Bool { items.isEmpty && !unreadableTypes.isEmpty }

    /// Puts the saved items back. Returns false if nothing could be written. Does nothing when the original
    /// content was unreadable, so that promised data is not replaced by an empty pasteboard.
    @discardableResult
    public func restore(to pasteboard: NSPasteboard) -> Bool {
        if isUnrestorable { return false }
        pasteboard.clearContents()
        guard !items.isEmpty else { return true }
        let objects: [NSPasteboardItem] = items.map { entry in
            let item = NSPasteboardItem()
            for (type, data) in entry.types { item.setData(data, forType: type) }
            return item
        }
        return pasteboard.writeObjects(objects)
    }

    /// Writes dictated text marked transient so clipboard managers that honour the convention ignore it.
    /// Returns the pasteboard change count after the write, or nil if the write failed.
    public static func writeTransient(text: String, to pasteboard: NSPasteboard) -> Int? {
        pasteboard.clearContents()
        let item = NSPasteboardItem()
        item.setString(text, forType: .string)
        item.setData(Data(), forType: transientType)
        item.setData(Data(), forType: autoGeneratedType)
        guard pasteboard.writeObjects([item]) else { return nil }
        return pasteboard.changeCount
    }
}
